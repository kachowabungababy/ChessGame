export function getEvolutionTierForStage(stageId = 1) {
  if (stageId <= 7) return 1;
  if (stageId <= 14) return 2;
  return 3;
}

export function getLineupForStage(stageId = 1, customPawnLineId = 'pichu_line') {
  const tier = getEvolutionTierForStage(stageId);
  const selectedPawnLine = PAWN_OPTIONS.find((l) => l.id === customPawnLineId) || PAWN_OPTIONS[0];
  const stageKey = `stage${tier}`;

  return {
    pawn: selectedPawnLine[stageKey],
    knight: KNIGHT_OPTIONS[0][stageKey],
    bishop: BISHOP_OPTIONS[0][stageKey],
    rook: ROOK_OPTIONS[0][stageKey],
    queen: QUEEN_OPTIONS[0][stageKey],
    king: KING_OPTIONS[0][stageKey],
    tier,
  };
}
